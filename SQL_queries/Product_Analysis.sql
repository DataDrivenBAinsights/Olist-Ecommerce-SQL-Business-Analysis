-- Task 8 – Product Revenue Concentration

WITH CategoryRevenue AS
(
    SELECT
        PC.column2 AS Product_category,
        SUM(OI.price + OI.freight_value) AS Revenue_per_category
    FROM Order_items OI
    JOIN Products P
        ON OI.product_id = P.product_id
    JOIN Product_category PC
        ON P.product_category_name = PC.column1
    GROUP BY PC.column2
)

SELECT
    Product_category,
    Revenue_per_category,
    ROUND(Revenue_per_category * 100.0 /SUM(Revenue_per_category) OVER (),2) AS Revenue_share,
    ROUND(
        SUM(Revenue_per_category) OVER (
            ORDER BY Revenue_per_category DESC
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) * 100.0 /SUM(Revenue_per_category) OVER (), 2)
            AS Cumulative_revenue_percentage
FROM CategoryRevenue
ORDER BY Revenue_per_category DESC;

/*
-- Pareto Analysis
Pareto analysis reveals that revenue on the Olist marketplace is highly concentrated.
Approximately 24% of product categories (17 out of 71) generate 80.86% of total revenue, demonstrating a clear Pareto distribution.
The top five categories alone contribute nearly 40% of total marketplace revenue, led by Health & Beauty (9.22%), Watches & Gifts (8.35%), and Bed Bath Table (7.94%).
This concentration suggests that business growth and profitability depend heavily on a relatively small group of high-performing categories,
while the majority of categories contribute only marginally to overall revenue.
Many categories contribute less than 0.2% of total revenue individually, including:
Flowers, Home Comfort 2, CDs/DVDs/Musicals, Fashion Children's Clothes, Security & Services
Collectively, these categories represent a long tail of low-revenue products.
*/

/* Business Recommendation
1. Continue investing in high-performing categories while avoiding excessive dependence on them.
2. Develop growth strategies for mid-performing categories to diversify revenue sources.
3. Monitor category performance regularly to detect changes in customer demand.
*/


