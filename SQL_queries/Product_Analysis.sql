-- Task 2.2 Revenue per category
WITH OrderItemCount AS 
(SELECT order_id, 
        COUNT(*) AS Item_count
 FROM Order_items
 GROUP BY order_id )
SELECT PC.column2 AS Product_category,
       SUM(OP.payment_value / OIC.item_count) AS Revenue_per_category
FROM Order_items AS OI
JOIN OrderItemCount AS OIC
ON OI.order_id = OIC.order_id
JOIN Products AS P
ON OI.product_id = P.product_id
JOIN Product_category AS PC
ON P.product_category_name = PC.column1
JOIN Order_payments AS OP
ON OI.order_id = OP.order_id
GROUP BY PC.column2
ORDER BY Revenue_per_category DESC;

/* Insights
1.Health and Beauty is the highest revenue-generating category with USD 1.44M.
It is followed by Watches and Gifts (USD 1.30M) and Bed Bath Table (USD 1.24M).

2.Categories such as Security and Services (USD 325), Fashion Children's Clothes (USD 677), CDs/DVDs/Musicals (USD 954),
Flowers (USD 1.56K), and Arts and Craftsmanship (USD 2.18K) contribute only a tiny fraction of total revenue.
*/

-- Task 2.3 Revenue share(%) per category
WITH OrderItemCount AS 
( SELECT order_id,
         COUNT(*) AS Item_counts
  FROM Order_items
  GROUP BY order_id )

SELECT PC.column2 AS Product_category,
       SUM(OP.payment_value / OIC.Item_counts) AS Revenue_per_category,
       ROUND(SUM(OP.payment_value / OIC.Item_counts) * 100 /  SUM(SUM(OP.payment_value  / OIC.Item_counts)) OVER(),2) AS Revenue_share
FROM Order_items AS OI
JOIN OrderItemCount AS OIC
ON OI.order_id = OIC.order_id
JOIN Products AS P
ON OI.product_id = P.product_id
JOIN Product_category AS PC
ON P.product_category_name = PC.column1
JOIN Order_payments AS OP
ON OI.order_id = OP.order_id
GROUP BY PC.column2
ORDER BY Revenue_per_category DESC;

-- Insights 
-- Over 60 % of generated by Top 10 categories
-- More than 40 categories each contribute less than 1% of total revenue.

/* Business Recommendation
1. Maintain optimal inventory levels for high-demand categories to avoid stockouts.
2. Prioritize these categories in marketing campaigns and seasonal promotions.
3. Expand the product assortment within top-performing categories to capture additional demand.
*/


