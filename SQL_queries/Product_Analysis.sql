--Task 4 – High Revenue vs High Volume

WITH CategorySales AS
( SELECT PC.column2 AS Product_category,
         SUM(OP.payment_value) AS Total_revenue,
         COUNT(*) AS Units_sold,
         ROUND(SUM(OP.payment_value) * 1.0 /COUNT(*) ,2) AS Revenue_per_unit
 FROM Order_items AS OI
 JOIN Order_payments AS OP 
 ON OI.order_id = OP.order_id
 JOIN Products  AS P
 on OI.product_id = P.product_id
 JOIN Product_category AS PC
 ON P.product_category_name = PC.column1
 GROUP BY PC.column2)
 SELECT * ,
       CASE
            WHEN Revenue_per_unit > 200 THEN 'Premium product category'
            WHEN Revenue_per_unit BETWEEN '99' AND '199' THEN 'Balanced'
            ELSE 'Volume  driven'
END AS Observation
FROM CategorySales
ORDER BY Total_revenue DESC;

-- Categories like Watches , Office furniture ,Computers generate revenue because of high prices.

-- categories like Electronics , Food rely on volumes to boost theie revenue

/* Business Recommendation
1. For premium categories, focus on premium branding, customer experience, and value-added services.
2. For volume-driven categories, optimize pricing and inventory turnover to maximize sales.
3. Use different marketing strategies for premium and volume-based categories.
*/


